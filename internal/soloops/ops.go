package soloops

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"strings"
	"time"
)

// Inquiry is a CRM lead row.
type Inquiry struct {
	ID        string `json:"id"`
	Name      string `json:"name"`
	Event     string `json:"event"`
	Guests    int    `json:"guests"`
	Status    string `json:"status"`
	CreatedAt string `json:"created_at"`
	Notes     string `json:"notes,omitempty"`
}

// PolicyPack is a generated policy artifact.
type PolicyPack struct {
	Business string   `json:"business"`
	Sections []string `json:"sections"`
	Markdown string   `json:"markdown"`
}

func NewInquiry(id, name, event string, guests int, notes string) Inquiry {
	if id == "" {
		id = fmt.Sprintf("inq-%d", time.Now().UnixNano())
	}
	if guests < 0 {
		guests = 0
	}
	return Inquiry{
		ID:        id,
		Name:      strings.TrimSpace(name),
		Event:     strings.TrimSpace(event),
		Guests:    guests,
		Status:    "new",
		CreatedAt: time.Now().UTC().Format(time.RFC3339),
		Notes:     notes,
	}
}

func AppendInquiry(path string, inq Inquiry) error {
	f, err := os.OpenFile(path, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	b, err := json.Marshal(inq)
	if err != nil {
		return err
	}
	_, err = f.Write(append(b, '\n'))
	return err
}

func ListInquiries(path string) ([]Inquiry, error) {
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	defer f.Close()
	var out []Inquiry
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		var inq Inquiry
		if err := json.Unmarshal([]byte(line), &inq); err != nil {
			continue
		}
		out = append(out, inq)
	}
	return out, sc.Err()
}

// GeneratePolicyPack builds a simple offline policy markdown artifact.
func GeneratePolicyPack(business string) PolicyPack {
	sections := []string{
		"Booking & deposits",
		"Cancellation",
		"Photo release",
		"Hygiene & safety",
		"Travel radius",
	}
	var b strings.Builder
	b.WriteString("# Operations Policy Pack — " + business + "\n\n")
	b.WriteString("_Generated by Solo Ops. Replace bracketed fields before publishing._\n\n")
	for _, s := range sections {
		b.WriteString("## " + s + "\n\n")
		b.WriteString("- Owner: [" + business + "]\n")
		b.WriteString("- Policy text: [draft]\n\n")
	}
	return PolicyPack{Business: business, Sections: sections, Markdown: b.String()}
}
