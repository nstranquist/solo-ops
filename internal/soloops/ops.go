package soloops

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"strings"
	"time"
)

// Inquiry is a CRM lead row.
type Inquiry struct {
	ID        string `json:"id"`
	Name      string `json:"name"`
	Event     string `json:"event"`
	Guests    int    `json:"guests"`
	Status    string `json:"status"`
	CreatedAt string `json:"created_at"`
	UpdatedAt string `json:"updated_at,omitempty"`
	Notes     string `json:"notes,omitempty"`
}

// PolicyPack is a generated policy artifact.
type PolicyPack struct {
	Business string   `json:"business"`
	Sections []string `json:"sections"`
	Markdown string   `json:"markdown"`
}

func NewInquiry(id, name, event string, guests int, notes string) Inquiry {
	if id == "" {
		id = fmt.Sprintf("inq-%d", time.Now().UnixNano())
	}
	if guests < 0 {
		guests = 0
	}
	now := time.Now().UTC().Format(time.RFC3339)
	return Inquiry{
		ID: id, Name: strings.TrimSpace(name), Event: strings.TrimSpace(event),
		Guests: guests, Status: "new", CreatedAt: now, UpdatedAt: now, Notes: notes,
	}
}

func AppendInquiry(path string, inq Inquiry) error {
	f, err := os.OpenFile(path, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	b, err := json.Marshal(inq)
	if err != nil {
		return err
	}
	_, err = f.Write(append(b, '\n'))
	return err
}

func ListInquiries(path string) ([]Inquiry, error) {
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	defer f.Close()
	// last write wins per id
	byID := map[string]Inquiry{}
	order := []string{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		var inq Inquiry
		if err := json.Unmarshal([]byte(line), &inq); err != nil {
			continue
		}
		if _, ok := byID[inq.ID]; !ok {
			order = append(order, inq.ID)
		}
		byID[inq.ID] = inq
	}
	var out []Inquiry
	for _, id := range order {
		out = append(out, byID[id])
	}
	return out, sc.Err()
}

// SetStatus appends a status update event for an inquiry id.
func SetStatus(path, id, status string) (Inquiry, error) {
	list, err := ListInquiries(path)
	if err != nil {
		return Inquiry{}, err
	}
	var found *Inquiry
	for i := range list {
		if list[i].ID == id {
			found = &list[i]
			break
		}
	}
	if found == nil {
		return Inquiry{}, fmt.Errorf("inquiry %s not found", id)
	}
	upd := *found
	upd.Status = strings.TrimSpace(status)
	upd.UpdatedAt = time.Now().UTC().Format(time.RFC3339)
	if err := AppendInquiry(path, upd); err != nil {
		return Inquiry{}, err
	}
	return upd, nil
}

func GeneratePolicyPack(business string) PolicyPack {
	sections := []string{
		"Booking & deposits", "Cancellation", "Photo release", "Hygiene & safety", "Travel radius",
	}
	var b strings.Builder
	b.WriteString("# Operations Policy Pack — " + business + "\n\n")
	b.WriteString("_Generated by Solo Ops. Replace bracketed fields before publishing._\n\n")
	for _, s := range sections {
		b.WriteString("## " + s + "\n\n- Owner: [" + business + "]\n- Policy text: [draft]\n\n")
	}
	return PolicyPack{Business: business, Sections: sections, Markdown: b.String()}
}
